export function randomCategory(exclude = []) {
  const keys = Object.keys(CATEGORIES).filter((k) => !exclude.includes(k))
  const pool = keys.length ? keys : Object.keys(CATEGORIES)
  return pool[Math.floor(Math.random() * pool.length)]
}

export function pickWordPair(category, recentKeys = []) {
  const words = CATEGORIES[category]
  const n = words.length
  let i, j, key
  let attempts = 0
  do {
    i = Math.floor(Math.random() * n)
    j = Math.floor(Math.random() * n)
    key = `${category}:${Math.min(i, j)}-${Math.max(i, j)}`
    attempts++
  } while ((i === j || recentKeys.includes(key)) && attempts < 50)
  if (i === j) j = (i + 1) % n
  return { key, normalWord: words[i], outsiderWord: words[j] }
}
