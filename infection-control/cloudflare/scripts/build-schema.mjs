// Turns cloudflare/schema.txt into:
//   cloudflare/schema.sql      — CREATE TABLE statements for D1 (SQLite)
//   cloudflare/worker/schema.js — column map the Worker uses to validate
//                                 queries and convert booleans / JSON.
// Usage: node cloudflare/scripts/build-schema.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const lines = readFileSync(join(root, "schema.txt"), "utf8")
  .split("\n")
  .filter((l) => l.trim() && !l.startsWith("#"));

// Unique constraints from Supabase (needed for upsert onConflict targets).
const UNIQUE = {
  checklist_types: [["code"]],
  employee_clinic_status: [["employee_id"]],
  employee_health_records: [["employee_id", "item_type_id", "dose_number"]],
  employee_vaccine_requests: [["employee_id", "item_type_id"]],
  hai_monthly_indicators: [["category", "month"]],
  hai_vae_monitoring: [["icu_surveillance_id", "date"]],
  ic_test_access: [["employee_id"]],
  ic_test_sets: [["department"]],
  stock_daily_checks: [["date", "item_id"]],
  users: [["username"]],
};
// Plain indexes for the columns pages filter on most.
const INDEX = {
  cbahi_standards_tracker: [["seq"]],
  ica_standards_tracker: [["seq"]],
  employee_nsi_followups: [["employee_id"]],
  employee_health_records: [["employee_id"]],
  employee_vaccine_requests: [["employee_id"]],
  ipc_calendar_tasks: [["task_date"], ["created_by"]],
  messages: [["sender_username"], ["recipient_username", "read_at"]],
  stock_daily_checks: [["item_id"], ["department", "date"]],
  stock_requests: [["department", "date"], ["item_id"]],
  stock_items: [["department"]],
  ic_test_attempts: [["employee_id"]],
};

const SQL_TYPE = { u: "TEXT", s: "TEXT", d: "TEXT", z: "TEXT", h: "TEXT", j: "TEXT", b: "INTEGER", i: "INTEGER", n: "REAL" };

const tables = {};
let sql = "-- Generated by cloudflare/scripts/build-schema.mjs — do not edit by hand.\nPRAGMA foreign_keys = OFF;\n\n";

for (const line of lines) {
  const [table, colSpec] = line.split("|");
  const cols = {};
  const defs = [];
  for (const raw of colSpec.split(";")) {
    const m = raw.match(/^([a-z0-9_]+):([usdzbinjh])(!?)(?:=(.*))?$/);
    if (!m) throw new Error(`Bad column spec in ${table}: ${raw}`);
    const [, name, t, bang, def] = m;
    const col = { t };
    if (bang) col.nn = 1;
    if (def !== undefined) col.def = def; // literal text, or @uuid/@now/@today
    cols[name] = col;
    // SQLite gets only structural constraints. Defaults are applied by the
    // Worker on insert (so @uuid/@now/@today and JSON literals behave the
    // same as Postgres) — but a static SQL default is still added for plain
    // literals so manual imports behave too.
    let d = `"${name}" ${SQL_TYPE[t]}`;
    if (name === "id" || (table === "app_config" && name === "id")) d += " PRIMARY KEY";
    if (def !== undefined && !def.startsWith("@")) {
      let lit;
      if (t === "b") lit = def === "true" ? "1" : "0";
      else if (t === "i" || t === "n") lit = def;
      else lit = `'${def.replace(/'/g, "''")}'`;
      d += ` DEFAULT ${lit}`;
    }
    defs.push(d);
  }
  for (const u of UNIQUE[table] || []) defs.push(`UNIQUE (${u.map((c) => `"${c}"`).join(", ")})`);
  sql += `CREATE TABLE IF NOT EXISTS "${table}" (\n  ${defs.join(",\n  ")}\n);\n`;
  for (const ix of INDEX[table] || []) {
    sql += `CREATE INDEX IF NOT EXISTS "${table}_${ix.join("_")}_idx" ON "${table}" (${ix.map((c) => `"${c}"`).join(", ")});\n`;
  }
  sql += "\n";
  tables[table] = { cols, unique: UNIQUE[table] || [] };
}

writeFileSync(join(root, "schema.sql"), sql);
writeFileSync(
  join(root, "worker", "schema.js"),
  "// Generated by cloudflare/scripts/build-schema.mjs — do not edit by hand.\nexport const TABLES = " +
    JSON.stringify(tables, null, 0).replace(/\},"/g, '},\n"') +
    ";\n"
);
console.log(`Wrote ${Object.keys(tables).length} tables.`);
